-- CREATE RAILWAY BOOKING TABLE

CREATE TABLE Railway_Booking (
    Booking_ID INT PRIMARY KEY,
    Passenger_Name VARCHAR(50),
    Train_No INT,
    Journey_Date DATE,
    From_City VARCHAR(50),
    To_City VARCHAR(50),
    Seat_No INT
);

